export const UI: Record<Locale, Dict> = { es, en };
export type UIKey = keyof typeof es;

export function t(lang: Locale, key: UIKey, vars: Record<string, string | number> = {}): string {
  let s = UI[lang][key] ?? UI.es[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function formatDate(lang: Locale, iso: string | null | undefined): string {
  if (!iso) return '—';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '—';
  return d.toLocaleDateString(lang === 'es' ? 'es-419' : 'en-US', { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' });
}
